"""
summarizer.py — Summarise research papers using IBM Granite.

Provides:
- Abstract-level summaries
- Full-paper summaries (chunked for long texts)
- Comparative summaries across multiple papers
- Key-findings extraction
"""

import logging
from typing import List

from research_agent.granite_client import GraniteClient
from research_agent.tools.literature_search import Paper

logger = logging.getLogger(__name__)

_SYSTEM_SUMMARISE = (
    "You are an expert academic research assistant powered by IBM Granite. "
    "Your task is to summarise research papers clearly and concisely for "
    "scientists and engineers. Focus on: (1) research problem, (2) methodology, "
    "(3) key findings, (4) contributions, and (5) limitations."
)

_SYSTEM_COMPARE = (
    "You are an expert academic research assistant powered by IBM Granite. "
    "Compare and contrast the provided research papers. Highlight: common themes, "
    "differences in methodology, conflicting findings, and research gaps."
)

_SYSTEM_FINDINGS = (
    "You are an expert academic research assistant powered by IBM Granite. "
    "Extract and list the key findings, contributions, and conclusions from the "
    "given abstract or paper text. Use bullet points."
)


class SummarizerTool:
    """
    Summarises individual papers or a collection using IBM Granite.

    Parameters
    ----------
    client : GraniteClient
        An initialised GraniteClient instance.
    """

    def __init__(self, client: GraniteClient) -> None:
        self._client = client

    # ── Public API ────────────────────────────────────────────────────────────

    def summarise_paper(self, paper: Paper, detailed: bool = False) -> str:
        """
        Generate a summary for a single Paper object.

        Parameters
        ----------
        paper : Paper
        detailed : bool
            If True, request a more detailed paragraph-level summary.

        Returns
        -------
        str
            The Granite-generated summary.
        """
        text = paper.abstract or "(No abstract available)"
        detail_instruction = (
            "Write a detailed 3-5 paragraph summary."
            if detailed
            else "Write a concise 1-2 paragraph summary."
        )
        user_msg = (
            f"Paper title: {paper.title}\n"
            f"Authors: {', '.join(paper.authors[:5])}\n"
            f"Year: {paper.year or 'Unknown'}\n"
            f"Venue: {paper.venue or 'Unknown'}\n\n"
            f"Abstract:\n{text}\n\n"
            f"{detail_instruction}"
        )
        logger.info("Summarising paper: '%s'", paper.title[:60])
        return self._client.generate_with_system(_SYSTEM_SUMMARISE, user_msg)

    def summarise_text(self, text: str, max_words: int = 200) -> str:
        """
        Summarise arbitrary text (e.g. extracted PDF content).

        Parameters
        ----------
        text : str
            Raw text to summarise.
        max_words : int
            Approximate target word count for the summary.

        Returns
        -------
        str
        """
        # Chunk if very long
        if len(text) > 4000:
            text = text[:4000] + "\n\n[... text truncated for length ...]"
        user_msg = (
            f"Please summarise the following research text in approximately "
            f"{max_words} words:\n\n{text}"
        )
        return self._client.generate_with_system(_SYSTEM_SUMMARISE, user_msg)

    def extract_key_findings(self, paper: Paper) -> str:
        """
        Extract key findings and contributions from a paper's abstract.

        Returns
        -------
        str
            Bulleted list of key findings generated by Granite.
        """
        text = paper.abstract or "(No abstract available)"
        user_msg = (
            f"Title: {paper.title}\n\n"
            f"Abstract:\n{text}\n\n"
            "List the key findings and contributions as bullet points."
        )
        logger.info("Extracting findings from: '%s'", paper.title[:60])
        return self._client.generate_with_system(_SYSTEM_FINDINGS, user_msg)

    def compare_papers(self, papers: List[Paper]) -> str:
        """
        Generate a comparative analysis across multiple papers.

        Parameters
        ----------
        papers : list of Paper
            Two or more papers to compare.

        Returns
        -------
        str
            Comparative summary generated by Granite.
        """
        if len(papers) < 2:
            raise ValueError("At least 2 papers are required for comparison.")

        entries = []
        for i, paper in enumerate(papers[:6], start=1):  # cap at 6 for prompt size
            entries.append(
                f"Paper {i}: {paper.title}\n"
                f"Authors: {', '.join(paper.authors[:3])}\n"
                f"Year: {paper.year or 'Unknown'}\n"
                f"Abstract: {(paper.abstract or '')[:600]}"
            )

        user_msg = "Compare and contrast the following research papers:\n\n" + "\n\n---\n\n".join(entries)
        logger.info("Comparing %d papers.", len(papers))
        return self._client.generate_with_system(_SYSTEM_COMPARE, user_msg, max_tokens=1500)
